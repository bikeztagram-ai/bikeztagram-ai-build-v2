import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { loadAiderState, saveAiderState } from '../../builder/runner/aider-state-store.mjs';

const root=fs.mkdtempSync(path.join(os.tmpdir(),'bikeztagram-aider-state-'));
const statePath=path.join(root,'state.json');
const defaults={protocol:'test',completed:[],failed:[],runs:0};
const first={protocol:'test',completed:['cinematic-quality'],failed:[],runs:1};
saveAiderState(statePath,first);
let loaded=loadAiderState(statePath,defaults);
if(loaded.source!=='main'||loaded.state.runs!==1)throw new Error('fresh state did not load from main');
fs.writeFileSync(statePath,'{"protocol":"test","completed":[');
loaded=loadAiderState(statePath,defaults);
if(!loaded.recovered||loaded.source!=='backup'||loaded.state.runs!==1)throw new Error('corrupt main state did not recover from backup');
const second={protocol:'test',completed:['cinematic-quality','editor-reliability'],failed:[],runs:2};
saveAiderState(statePath,second);
fs.writeFileSync(`${statePath}.tmp`,JSON.stringify({...second,runs:3}));
fs.writeFileSync(statePath,'{"broken":');
loaded=loadAiderState(statePath,defaults);
if(!loaded.recovered||loaded.source!=='temp'||loaded.state.runs!==3)throw new Error('valid temp state did not recover after torn main write');
fs.writeFileSync(statePath,'broken');
fs.writeFileSync(`${statePath}.tmp`,'broken');
fs.writeFileSync(`${statePath}.bak`,'broken');
loaded=loadAiderState(statePath,defaults);
if(!loaded.recovered||loaded.source!=='fresh'||loaded.state.runs!==0)throw new Error('fully corrupted state did not fail safe to fresh state');
saveAiderState(statePath,second);
const persisted=JSON.parse(fs.readFileSync(statePath,'utf8'));
if(persisted.runs!==2||persisted.completed.length!==2)throw new Error('atomic state save did not persist expected data');
fs.rmSync(root,{recursive:true,force:true});
console.log('aider-state-recovery: PASS');
