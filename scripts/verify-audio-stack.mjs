import assert from 'node:assert/strict';
import { buildAudioDirection } from '../src/audioDirector.js';
import { buildAudioMixPlan } from '../src/audioMixPlan.js';
import { buildAudioTimeline } from '../src/audioTimeline.js';
import { buildCompleteAudioSystem } from '../src/audioSystem.js';
import { classifyAudioAsset } from '../src/audioAssetPolicy.js';
const cuts=[{startTime:0,editorialRole:'hook'},{startTime:3.2,editorialRole:'build'},{startTime:6.1,editorialRole:'reveal'},{startTime:10,editorialRole:'action'},{startTime:13,editorialRole:'hero'}];
const direction=buildAudioDirection({creativePrompt:'dark cinematic energetic reveal',duration:15});
assert.ok(direction.beatGrid.length>0);
const mix=buildAudioMixPlan({audioDirection:direction,hasVoiceover:true,hasSfx:true});
assert.equal(mix.master.targetLufs,-14);
const timeline=buildAudioTimeline({audioDirection:direction,cuts,mixPlan:mix});
assert.equal(timeline.events.filter(e=>e.type==='cut').length,5);
const system=buildCompleteAudioSystem({creativePrompt:'cinematic trailer',duration:15,cuts});
assert.equal(system.version,'audio-system-v1');
assert.equal(classifyAudioAsset({userSupplied:true}).allowed,true);
assert.equal(classifyAudioAsset({source:'known-song'}).allowed,false);
assert.equal(classifyAudioAsset({source:'original-generated'}).allowed,true);
console.log('audio-stack: PASS');
