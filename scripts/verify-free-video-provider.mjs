import fs from 'node:fs';
import assert from 'node:assert/strict';
const read = (path) => fs.readFileSync(new URL(path, import.meta.url), 'utf8');
const api = read('../api/video.js');
const client = read('../src/aiVideoProvider.js');
const adapter = read('../src/huggingFaceVideoProvider.js');
const space = read('../hf-space-video/app.py');
const readme = read('../hf-space-video/README.md');
assert.match(api, /HF_VIDEO_SPACE_URL/, 'preflight must expose the configured Space URL');
assert.match(api, /HF_VIDEO_API_NAME/, 'preflight must expose the configured endpoint name');
assert.match(client, /Boolean\(free\?\.configured&&free\?\.url\)/, 'auto provider must prefer a configured free Space');
assert.match(client, /!allowPaidVideo\)throw new Error/, 'Runway must remain locked when no free provider is available');
assert.match(adapter, /\/gradio_api\/upload/, 'reference images must be uploaded using Gradio file API');
assert.match(adapter, /\/gradio_api\/call/, 'generation must use the Gradio queue API');
assert.match(adapter, /type === 'complete'/, 'adapter should parse completed queue results');
assert.match(adapter, /startsWith\('video\/'\)/, 'adapter must reject empty/non-video outputs');
assert.match(space, /Wan-AI\/Wan2\.2-TI2V-5B-Diffusers/, 'Space must use the intended open video model');
assert.match(space, /@spaces\.GPU\(duration=180\)/, 'Space must use bounded ZeroGPU allocation');
assert.match(space, /api_name="generate_video"/, 'Space must expose the stable generate_video endpoint');
assert.match(readme, /HF_VIDEO_SPACE_URL/, 'Space deployment instructions must document app integration');
console.log('PASS: free-first Hugging Face video provider contract');
